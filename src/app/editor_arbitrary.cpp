				VariableGuard<decltype(style.ItemSpacing)> guardItemSpacing(&style.ItemSpacing, style.ItemSpacing, ImVec2(8, 4));

				ImGui::SetNextItemWidth(ImGui::GetContentRegionAvail().x - 19 - 1 * 2 - 43);
